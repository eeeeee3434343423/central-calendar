export function icon(name, size = 16, extraClass = '') {
  const span = document.createElement('span');
  span.className = `icon ${extraClass}`.trim();
  span.setAttribute('aria-hidden', 'true');
  span.innerHTML = `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${P[name] || ''}</svg>`;
  return span;
}

export function iconButton(name, label, onClick, { size = 16, cls = '', pressed } = {}) {
  const b = h(`button.btn-icon${cls ? '.' + cls.split(' ').join('.') : ''}`, { type: 'button', 'aria-label': label, title: label, on: { click: onClick } }, icon(name, size));
  if (pressed !== undefined) b.setAttribute('aria-pressed', String(!!pressed));
  return b;
}

/** Readable text color on a solid calendar color. */
export function onColor(hex) {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex || '');
  if (!m) return '#fff';
  const n = parseInt(m[1], 16);
  const lin = (c) => {
    const v = c / 255;
    return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
  };
  const L = 0.2126 * lin((n >> 16) & 255) + 0.7152 * lin((n >> 8) & 255) + 0.0722 * lin(n & 255);
  return L > 0.45 ? '#1c1c1e' : '#fff';
}

/** CSS custom properties for anything tinted by a calendar color. */
export function calVars(color) {
  return { '--c': color, '--on-c': onColor(color) };
}

export function clear(el) {
  while (el.firstChild) el.removeChild(el.firstChild);
  return el;
}

export function isTyping(target) {
  const t = target || document.activeElement;
  if (!t || !t.tagName) return false;
  return t.isContentEditable || ['INPUT', 'TEXTAREA', 'SELECT'].includes(t.tagName);
}

/** Download a text file to the viewer's device. */
export function downloadText(filename, text, type = 'text/plain') {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const a = h('a', { href: url, download: filename });
  document.body.append(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/** Ask for a file and read it as text. Resolves { name, text } or null. */
export function pickTextFile(accept) {
  return new Promise((resolve) => {
    const input = h('input', { type: 'file', accept, style: { display: 'none' } });
    input.addEventListener('change', async () => {
      const f = input.files && input.files[0];
      input.remove();
      if (!f) return resolve(null);
      resolve({ name: f.name, text: await f.text() });
    });
    document.body.append(input);
    input.click();
  });
}
